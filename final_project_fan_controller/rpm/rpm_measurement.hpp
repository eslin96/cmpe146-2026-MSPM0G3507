#pragma once

#include <cstdint>

namespace fan_controller {

/**
 * @brief One RPM measurement delivered to the control and display tasks.
 *
 * A zero RPM value is valid. The validity flag describes whether the
 * measurement configuration and time window were valid; stall detection is a
 * separate responsibility of the system-integration task.
 */
struct rpm_reading
{
  std::uint32_t rpm;
  bool valid;
};

/**
 * @brief Convert a counted number of tachometer pulses into RPM.
 *
 * @param p_pulse_count Number of tachometer edges counted in the window.
 * @param p_pulses_per_revolution Tachometer edges generated by one revolution.
 * @param p_window_ms Measurement-window length in milliseconds.
 */
[[nodiscard]] rpm_reading calculate_rpm(std::uint32_t p_pulse_count,
                                        std::uint32_t p_pulses_per_revolution,
                                        std::uint32_t p_window_ms);

}  // namespace fan_controller
